/** City-level system prompt — includes retrieved case context when available */
function buildCitySystemPrompt(retrievedContext?: string): string {
  const contextBlock = retrievedContext
    ? `\n\n${retrievedContext}\n\nUse the retrieved cases above to ground your answer in real data.`
    : ''
  return `You are CivicLens Assistant, an expert civic data analyst for Bengaluru.
You help ward officials, journalists, and concerned citizens understand civic issues,
BBMP ward data, complaint trends, and public infrastructure challenges in Bengaluru.
Complaint data covers 2019–2022 (I Change My City platform). Priority scores are
machine-generated by CivicLens: 0–1 scale, higher = more urgent. HIGH ≥ 0.5, LOW < 0.3.

RULES:
1. Ground every claim in the data provided — do not invent ward names, scores, or statistics.
2. If you make an inference, explicitly label it "Inference:" or "Likely reason:".
3. Be concise and direct. Use plain English. Avoid jargon.
4. If asked about a specific case in depth, tell the user to select it from the cases list.
5. Never say you "don't have access to the database" — you have the retrieved cases below.
${WIDGET_INSTRUCTIONS}${contextBlock}`
}

/** Build a rich system prompt grounded in real case data */
function buildSystemPrompt(c: CaseFull, _row: CaseRow): string {
  const factors = Object.entries(c.priority_factors)
    .map(([k, v]) => `  ${k}: ${(v * 100).toFixed(0)}%`)
    .join('\n')

  const evidence = c.evidence_items
    .map(e => `  [${e.type}] ${e.description}`)
    .join('\n')

  const workOrders = c.work_orders_detail?.slice(0, 5)
    .map(wo => `  WO#${wo.work_order_id} FY${wo.fy ?? '?'} ₹${wo.sanctioned_crore ?? '?'}Cr — ${(wo.description ?? '').substring(0, 80)}`)
    .join('\n') ?? '  None available'

  const hyps = c.hypotheses.length
    ? c.hypotheses.map(h => `  ${h}`).join('\n')
    : '  None'

  return `You are CivicLens Assistant, an expert civic data analyst for Bengaluru.
You have access to the full machine-generated data for a specific civic case.
Your job is to explain clearly and honestly WHY this case has its priority tier,
what the data actually shows, and what it means in plain English for a ward
official, journalist, or concerned citizen.

RULES:
1. Ground every claim in the data provided below — do not invent statistics.
2. If you make an inference, explicitly label it "Inference:" or "Likely reason:".
3. Do not assert contractor misconduct from deductions or blacklist flags alone.
4. Do not claim a specific work order fixed or caused a specific complaint.
5. Be concise and direct. Use plain English. Avoid jargon.
6. If asked something outside this case data, say you don't have that information.
${WIDGET_INSTRUCTIONS}

═══ CASE DATA ═══════════════════════════════════════════════════════
Case ID:        ${c.case_id}
Title:          ${c.problem_title}
Priority tier:  ${c.priority_tier}
Priority score: ${c.priority_score.toFixed(3)} (scale 0–1, higher = more urgent)
Ward:           ${c.primary_ward_name ?? 'unknown'} (ward join: ${c.ward_join_confidence})
Agency:         ${c.responsible_agency ?? 'unknown'} (${c.agency_confidence} attribution)

COMPLAINT STATISTICS:
  Total complaints:  ${c.complaint_count}
  Open / unresolved: ${c.open_count} (${c.unresolved_rate_pct}%)
  Resolved:          ${c.resolved_count}
  Re-opened:         ${c.reopened_count}
  Years active:      ${c.years_active.join(', ')}

PRIORITY FACTOR SCORES (0–100%, what drove the score):
${factors}

RATIONALE (machine-generated):
  ${c.priority_rationale}

EVIDENCE:
${evidence}

WARD-LEVEL WORK ORDERS (from KAUN BBMP — ward-level only, cannot be linked to this cluster):
${workOrders}

HYPOTHESES (explicitly unverified):
${hyps}

NOTE: Complaint data is from 2019–2022 (I Change My City). Work orders are from
2023–2026 (KAUN BBMP). There is a temporal gap; work orders may not relate to
these complaints.
═══════════════════════════════════════════════════════════════════`
}

/** Call the OpenAI-compatible endpoint */
async function callAI(messages: Message[]): Promise<string> {
  if (!AI_ENDPOINT || !AI_KEY) throw new Error('AI not configured')
  const res = await fetch(AI_ENDPOINT, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${AI_KEY}`,
    },
    body: JSON.stringify({
      model: AI_MODEL,
      messages,
      max_tokens: 900,
      temperature: 0.3,
    }),
  })
  if (!res.ok) {
    const txt = await res.text().catch(() => '')
    throw new Error(`AI API error ${res.status}: ${txt.slice(0, 200)}`)
  }
  const data = await res.json()
  return data.choices?.[0]?.message?.content || '(empty response)'
}

