// ── Widget renderer ───────────────────────────────────────────────────────────
interface WidgetData { label: string; value: number; color?: string }
interface WidgetSpec { type: 'bar' | 'pie' | 'stat'; title: string; data: WidgetData[] }

function WidgetRenderer({ spec }: { spec: WidgetSpec }) {
  const { type, title, data } = spec

  if (type === 'stat') {
    return (
      <div className="my-2 rounded-xl border border-blue-100 bg-blue-50 p-3">
        <p className="text-[10px] font-semibold text-blue-600 uppercase tracking-wide mb-2">{title}</p>
        <div className="flex gap-3 flex-wrap">
          {data.map((d, i) => (
            <div key={i} className="flex-1 min-w-[70px] text-center bg-white rounded-lg px-2 py-2 border border-blue-100">
              <p className="text-[20px] font-bold text-gray-800 leading-none">{d.value}</p>
              <p className="text-[10px] text-gray-500 mt-1 leading-tight">{d.label}</p>
            </div>
          ))}
        </div>
      </div>
    )
  }

  if (type === 'bar') {
    const max = Math.max(...data.map(d => d.value), 0.001)
    return (
      <div className="my-2 rounded-xl border border-gray-200 bg-white p-3">
        <p className="text-[10px] font-semibold text-gray-500 uppercase tracking-wide mb-2">{title}</p>
        <div className="space-y-1.5">
          {data.map((d, i) => (
            <div key={i} className="flex items-center gap-2">
              <span className="text-[11px] text-gray-600 w-28 shrink-0 truncate text-right">{d.label}</span>
              <div className="flex-1 bg-gray-100 rounded-full h-4 overflow-hidden">
                <div
                  className="h-full rounded-full transition-all"
                  style={{
                    width: `${(d.value / max) * 100}%`,
                    background: d.color ?? '#3b82f6',
                  }}
                />
              </div>
              <span className="text-[11px] text-gray-500 w-10 shrink-0">
                {Number.isInteger(d.value) ? d.value : d.value.toFixed(2)}
              </span>
            </div>
          ))}
        </div>
      </div>
    )
  }

  if (type === 'pie') {
    const total = data.reduce((s, d) => s + d.value, 0) || 1
    const COLORS = ['#3b82f6', '#f97316', '#22c55e', '#a855f7', '#eab308', '#ef4444']
    let cumAngle = -90
    const slices = data.map((d, i) => {
      const angle = (d.value / total) * 360
      const start = cumAngle
      cumAngle += angle
      return { ...d, startAngle: start, angle, color: d.color ?? COLORS[i % COLORS.length] }
    })
    function polarToXY(cx: number, cy: number, r: number, deg: number) {
      const rad = (deg * Math.PI) / 180
      return { x: cx + r * Math.cos(rad), y: cy + r * Math.sin(rad) }
    }
    const cx = 60, cy = 60, r = 50
    return (
      <div className="my-2 rounded-xl border border-gray-200 bg-white p-3">
        <p className="text-[10px] font-semibold text-gray-500 uppercase tracking-wide mb-2">{title}</p>
        <div className="flex items-center gap-4">
          <svg width={120} height={120} viewBox="0 0 120 120">
            {slices.map((s, i) => {
              if (s.angle >= 360) {
                return <circle key={i} cx={cx} cy={cy} r={r} fill={s.color} />
              }
              const p1 = polarToXY(cx, cy, r, s.startAngle)
              const p2 = polarToXY(cx, cy, r, s.startAngle + s.angle)
              const large = s.angle > 180 ? 1 : 0
              return (
                <path key={i}
                  d={`M${cx},${cy} L${p1.x},${p1.y} A${r},${r} 0 ${large},1 ${p2.x},${p2.y} Z`}
                  fill={s.color} stroke="white" strokeWidth={1}
                />
              )
            })}
          </svg>
          <div className="space-y-1">
            {slices.map((s, i) => (
              <div key={i} className="flex items-center gap-1.5">
                <span className="w-2.5 h-2.5 rounded-sm shrink-0" style={{ background: s.color }} />
                <span className="text-[11px] text-gray-600">{s.label}</span>
                <span className="text-[11px] text-gray-400 ml-1">{s.value}</span>
              </div>
            ))}
          </div>
        </div>
      </div>
    )
  }

  return null
}

// ── Markdown renderer ─────────────────────────────────────────────────────────
/** Splits response text into markdown segments and optional widget blocks,
 *  renders each appropriately. */
function MdContent({ text }: { text: string }) {
  // Split on ```widget ... ``` blocks first
  const WIDGET_RE = /```widget\n([\s\S]*?)```/g
  const segments: Array<{ kind: 'md'; text: string } | { kind: 'widget'; spec: WidgetSpec }> = []
  let last = 0, wm: RegExpExecArray | null
  while ((wm = WIDGET_RE.exec(text)) !== null) {
    if (wm.index > last) segments.push({ kind: 'md', text: text.slice(last, wm.index) })
    try {
      const spec = JSON.parse(wm[1].trim()) as WidgetSpec
      segments.push({ kind: 'widget', spec })
    } catch {
      segments.push({ kind: 'md', text: wm[0] }) // fall back to raw text
    }
    last = wm.index + wm[0].length
  }
  if (last < text.length) segments.push({ kind: 'md', text: text.slice(last) })

  if (segments.some(s => s.kind === 'widget')) {
    return (
      <div>
        {segments.map((s, si) =>
          s.kind === 'widget'
            ? <WidgetRenderer key={si} spec={s.spec} />
            : <MdLines key={si} text={s.text} />
        )}
      </div>
    )
  }

  return <MdLines text={text} />
}

/** Pure markdown-to-React line renderer (no widget detection) */
function MdLines({ text }: { text: string }) {
  const lines = text.split('\n')
  const nodes: React.ReactNode[] = []
  let i = 0

  // Inline: **bold**, *italic*, `code`
  function inlineFormat(raw: string): React.ReactNode[] {
    const parts: React.ReactNode[] = []
    const re = /(\*\*(.+?)\*\*|\*(.+?)\*|`([^`]+)`)/g
    let last = 0, m: RegExpExecArray | null
    while ((m = re.exec(raw)) !== null) {
      if (m.index > last) parts.push(raw.slice(last, m.index))
      if (m[2]) parts.push(<strong key={m.index}>{m[2]}</strong>)
      else if (m[3]) parts.push(<em key={m.index}>{m[3]}</em>)
      else if (m[4]) parts.push(<code key={m.index} className="bg-gray-200 text-gray-700 font-mono px-1 rounded text-[11px]">{m[4]}</code>)
      last = m.index + m[0].length
    }
    if (last < raw.length) parts.push(raw.slice(last))
    return parts
  }

  while (i < lines.length) {
    const line = lines[i]
    // skip blank lines (we add spacing via margins)
    if (line.trim() === '') { i++; continue }
    // HR
    if (/^---+$/.test(line.trim())) {
      nodes.push(<hr key={i} className="my-1.5 border-gray-300" />)
      i++; continue
    }
    // Heading
    const h = line.match(/^(#{1,3})\s+(.+)/)
    if (h) {
      const level = h[1].length
      const cls = level === 1 ? 'text-[13px] font-bold mt-2 mb-0.5' : level === 2 ? 'text-[12px] font-semibold mt-2 mb-0.5' : 'text-[11px] font-semibold mt-1.5 mb-0.5 text-gray-600'
      nodes.push(<p key={i} className={cls}>{inlineFormat(h[2])}</p>)
      i++; continue
    }
    // Bullet list — collect consecutive items
    if (/^[\*\-]\s+/.test(line)) {
      const items: React.ReactNode[] = []
      while (i < lines.length && /^[\*\-]\s+/.test(lines[i])) {
        items.push(<li key={i}>{inlineFormat(lines[i].replace(/^[\*\-]\s+/, ''))}</li>)
        i++
      }
      nodes.push(<ul key={`ul-${i}`} className="list-disc list-inside space-y-0.5 my-1 pl-1">{items}</ul>)
      continue
    }
    // Numbered list — collect consecutive items
    if (/^\d+\.\s+/.test(line)) {
      const items: React.ReactNode[] = []
      while (i < lines.length && /^\d+\.\s+/.test(lines[i])) {
        items.push(<li key={i}>{inlineFormat(lines[i].replace(/^\d+\.\s+/, ''))}</li>)
        i++
      }
      nodes.push(<ol key={`ol-${i}`} className="list-decimal list-inside space-y-0.5 my-1 pl-1">{items}</ol>)
      continue
    }
    // Plain paragraph
    nodes.push(<p key={i} className="mb-1">{inlineFormat(line)}</p>)
    i++
  }
  return <div className="space-y-0">{nodes}</div>
}

// ── Main component ────────────────────────────────────────────────────────────
interface AIChatPanelProps {
  selectedCase: CaseRow | null
  allCases: CaseRow[] | null
}

export function AIChatPanel({ selectedCase, allCases }: AIChatPanelProps) {
  const [messages, setMessages] = useState<Message[]>([])
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const [errorMsg, setErrorMsg] = useState<string | null>(null)
  const [fullCase, setFullCase] = useState<CaseFull | null>(null)
  const [loadingCase, setLoadingCase] = useState(false)
  const [ragStatus, setRagStatus] = useState<'idle' | 'retrieving' | 'ready'>('idle')
  const bottomRef = useRef<HTMLDivElement>(null)

  // Warm up the embedding model as soon as the panel mounts
  useEffect(() => { warmUp() }, [])

  // Load full case data when selection changes
  useEffect(() => {
    if (!selectedCase) { setFullCase(null); setMessages([]); return }
    setLoadingCase(true)
    setFullCase(null)
    setMessages([])
    fetchCaseFull(selectedCase.case_id)
      .then(c => { setFullCase(c); setLoadingCase(false) })
      .catch(() => { setLoadingCase(false) })
  }, [selectedCase?.case_id])

  // Scroll to bottom on new messages
  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [messages, loading])

  const send = useCallback(async (text: string) => {
    if (!text.trim() || loading) return
    setInput('')
    setErrorMsg(null)

    const userMsg: Message = { role: 'user', content: text.trim() }

    // Build conversation history with new user msg visible immediately
    const history = [...messages, userMsg]
    setMessages(history)
    setLoading(true)

    let sysContent: string
    if (fullCase && selectedCase) {
      // Case selected — use full case prompt, no RAG needed
      sysContent = buildSystemPrompt(fullCase, selectedCase)
    } else {
      // City-level — retrieve relevant cases via RAG
      setRagStatus('retrieving')
      try {
        const caseIds = await topKCaseIds(text.trim(), 5)
        const context = await fetchRetrievedContext(caseIds)
        sysContent = buildCitySystemPrompt(context)
      } catch {
        // RAG failure is non-fatal — fall back to base city prompt
        sysContent = buildCitySystemPrompt()
      }
      setRagStatus('ready')
    }

    const sysMsg: Message = { role: 'system', content: sysContent }

    try {
      const reply = await callAI([sysMsg, ...history])
      setMessages(prev => [...prev, { role: 'assistant', content: reply }])
    } catch (e: any) {
      setErrorMsg(e.message)
    } finally {
      setLoading(false)
      setRagStatus('idle')
    }
  }, [fullCase, selectedCase, messages, loading])

  if (!AI_AVAILABLE) return <SetupGuide />

  return (
    <div className="flex flex-col h-full min-h-0">
      {/* Header */}
      <div className="px-4 py-3 border-b border-gray-100 shrink-0">
        <p className="text-[12px] font-semibold text-gray-700 flex items-center gap-1.5">
          <span className="text-blue-500 text-[14px]">✦</span> AI Assistant
        </p>
        {selectedCase ? (
          <p className="text-[11px] text-gray-400 mt-0.5 line-clamp-1" title={selectedCase.problem_title}>
            {selectedCase.problem_title}
          </p>
        ) : (
          <p className="text-[11px] text-gray-400 mt-0.5">Ask about Bengaluru civic data</p>
        )}
      </div>

      {/* Chat messages */}
      <div className="flex-1 overflow-y-auto px-4 py-3 space-y-3 min-h-0">
        {loadingCase && (
          <p className="text-[12px] text-gray-400 text-center mt-4">Loading case data…</p>
        )}

        {!loadingCase && messages.length === 0 && (
          <div className="space-y-2 mt-1">
            <p className="text-[11px] text-gray-400 font-medium uppercase tracking-wide">Try asking:</p>
            {(selectedCase ? SUGGESTIONS_CASE : SUGGESTIONS_CITY).map(s => (
              <button
                key={s}
                onClick={() => send(s)}
                className="block w-full text-left text-[12px] text-blue-700 bg-blue-50 hover:bg-blue-100 border border-blue-100 rounded-lg px-3 py-2 leading-snug transition-colors"
              >
                {s}
              </button>
            ))}
          </div>
        )}

        {messages.map((m, i) => (
          <div key={i} className={`flex ${m.role === 'user' ? 'justify-end' : 'justify-start'}`}>
            <div className={[
              'max-w-[88%] rounded-xl px-3 py-2.5 text-[12px] leading-relaxed',
              m.role === 'user'
                ? 'bg-blue-600 text-white'
                : 'bg-gray-100 text-gray-800',
            ].join(' ')}>
              {m.role === 'user'
                ? m.content
                : <MdContent text={m.content} />}
            </div>
          </div>
        ))}

        {loading && (
          <div className="flex justify-start flex-col gap-1">
            {ragStatus === 'retrieving' && (
              <p className="text-[10px] text-blue-500 px-1 animate-pulse">✦ Searching case database…</p>
            )}
            <div className="bg-gray-100 rounded-xl px-3 py-2.5 text-[12px] text-gray-400 flex items-center gap-1.5">
              <span className="animate-pulse">●</span>
              <span className="animate-pulse" style={{ animationDelay: '0.2s' }}>●</span>
              <span className="animate-pulse" style={{ animationDelay: '0.4s' }}>●</span>
            </div>
          </div>
        )}

        {errorMsg && (
          <div className="bg-red-50 border border-red-200 rounded-lg px-3 py-2 text-[11px] text-red-700">
            Error: {errorMsg}
          </div>
        )}

        <div ref={bottomRef} />
      </div>

      {/* Input bar */}
      <div className="px-3 py-3 border-t border-gray-100 shrink-0">
        {messages.length > 0 && (
          <button
            onClick={() => setMessages([])}
            className="text-[10px] text-gray-400 hover:text-gray-600 mb-2 transition-colors"
          >
            ↺ Clear chat
          </button>
        )}
        <div className="flex gap-2">
          <input
            value={input}
            onChange={e => setInput(e.target.value)}
            onKeyDown={e => e.key === 'Enter' && !e.shiftKey && send(input)}
            disabled={loadingCase || loading}
            placeholder={selectedCase ? 'Ask about this case…' : 'Ask about Bengaluru civic data…'}
            className="flex-1 border border-gray-200 rounded-lg px-3 py-1.5 text-[12px] focus:outline-none focus:ring-2 focus:ring-blue-400/40 disabled:bg-gray-50 disabled:text-gray-400"
          />
          <button
            onClick={() => send(input)}
            disabled={!input.trim() || loadingCase || loading}
            className="px-3 py-1.5 bg-blue-600 text-white rounded-lg text-[12px] font-semibold hover:bg-blue-700 disabled:opacity-40 transition-colors"
          >
            Ask
          </button>
        </div>
      </div>
    </div>
  )
}
